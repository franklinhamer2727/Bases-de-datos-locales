-- 1) Unicidad por día (la PK ya lo impide; debe dar 0 filas)
SELECT FECHA_PROCESO, ID_OPERACION_CIERRE, COD_RUBRO, COUNT(*)
FROM dbo.BDS_SALDOS_OPERATIVOS_PRE_PROMEDIO_LIMPIO
WHERE FECHA_PROCESO BETWEEN '2026-10-01' AND '2026-10-31'
GROUP BY FECHA_PROCESO, ID_OPERACION_CIERRE, COD_RUBRO
HAVING COUNT(*) > 1;

-- 2) Completitud: N = 31 para todas (debe dar 0 filas)
SELECT ID_OPERACION_CIERRE, COD_RUBRO, COUNT(*) AS dias
FROM dbo.BDS_SALDOS_OPERATIVOS_PRE_PROMEDIO_LIMPIO
WHERE FECHA_PROCESO BETWEEN '2026-10-01' AND '2026-10-31'
GROUP BY ID_OPERACION_CIERRE, COD_RUBRO
HAVING COUNT(*) <> 31;
